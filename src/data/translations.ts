// Map node label translation helper
export function translateNodeLabel(label: string, lang: "it" | "en"): string {
  if (!label) return "";
  let workingLabel = label;

  // Strip node suffixes first if present
  let suffix = "";
  if (workingLabel.endsWith(" (Lotta)")) {
    workingLabel = workingLabel.replace(" (Lotta)", "");
    suffix = TRANSLATIONS[lang].suffixBattle;
  } else if (workingLabel.endsWith(" (Tecnica)")) {
    workingLabel = workingLabel.replace(" (Tecnica)", "");
    suffix = TRANSLATIONS[lang].suffixPowerup;
  } else if (workingLabel.endsWith(" (Recluta)")) {
    workingLabel = workingLabel.replace(" (Recluta)", "");
    suffix = TRANSLATIONS[lang].suffixRecruit;
  }

  // Mapping labels to translation dictionary keys
  const map: { [key: string]: keyof typeof TRANSLATIONS.it } = {
    "Rotolo di Benvenuto": "nodeWelcomeScroll",
    "Sentiero Sinistro": "nodeLeftPath",
    "Sentiero Destro": "nodeRightPath",
    "Radura Ovest": "nodeWestGlade",
    "Passo Centrale": "nodeCenterPass",
    "Radura Est": "nodeEastGlade",
    "Valico Estremo": "nodeExtremePass",
    "Bosco Celato": "nodeHiddenWoods",
    "Fiume Rapido": "nodeRapidRiver",
    "Rovine Antiche": "nodeAncientRuins",
    "Bivio Ovest": "nodeWestFork",
    "Bivio Centrale": "nodeCenterFork",
    "Bivio Est": "nodeEastFork",
    "Valle Occidentale": "nodeWestValley",
    "Valle Centrale": "nodeCenterValley",
    "Valle Orientale": "nodeEastValley",
    "Ramen Ichiraku": "nodeRamenIchiraku",
    "Ultima Difesa": "nodeLastDefense",

    // Bosses
    "Il Tradimento di Mizuki": "bossMizuki",
    "Specchi Diabolici: Haku": "bossHaku",
    "Il Demone della Nebbia: Zabuza": "bossZabuza",
    "L'invasione della Foglia: Orochimaru": "bossOrochimaruShippuden",
    "Il Risveglio dello Shukaku: Gaara (Boss Finale)": "bossGaaraKid",
    "Il Destino degli Uchiha: Itachi": "bossItachiShippuden",
    "Infiltrazione alla Pioggia: Jiraiya": "bossJiraiyaShippuden",
    "Scontro dei Sannin: Orochimaru": "bossOrochimaruSannin",
    "La vendetta degli Uchiha: Sasuke Susanoo": "bossSasukeSusanoo",
    "Il Controllo del Chakra: Naruto KCM": "bossNarutoKcm"
  };

  const key = map[workingLabel];
  if (key) {
    return (TRANSLATIONS[lang][key] as string) + suffix;
  }
  return label; // Fallback
}

