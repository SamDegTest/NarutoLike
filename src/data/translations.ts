// Map Ninja name translations
export function translateNinjaName(id: string, baseName: string, lang: "it" | "en"): string {
  // Translate the suffix bracket part if any
  if (lang === "en") return baseName; // Default data is in English syntax "Name (Kid)", "Name (Shippuden)"

  // Convert English suffixes to Italian
  let result = baseName;
  result = result.replace("(Kid)", "(Bambino)");
  result = result.replace("(Shippuden)", "(Shippuden)");
  result = result.replace("(Sage Mode)", "(Modalità Eremitica)");
  result = result.replace("(Mangekyou)", "(Mangekyou)");
  result = result.replace("(Rinnegan)", "(Rinnegan)");
  result = result.replace("(Hebi)", "(Hebi)");
  result = result.replace("(Taka)", "(Taka)");
  result = result.replace("(Sannin)", "(Sannin)");
  result = result.replace("(Sage)", "(Eremita)");

  return result;
}
